// Bosses (every 5th wave). Big multi-part sprites in the enemies.js style: LEFT half authored + mirrored, right
// half one shade darker (light from the upper-left), k outline, magenta = hostile energy. Format: see ../bake.js.
// Maps were blocked out with a throwaway plate/bevel generator, then committed as plain text maps (edit them directly).
import { expandRows } from '../bake.js';

const SHADE = { 6: '5', 5: '4', 4: '3', 3: '2', 2: '1', x: 'V', V: 'v', v: 'u' };
function lit(rows, sym = 'even') {
    const full = expandRows(rows, sym);
    const half = Math.ceil(full[0].length / 2);
    return full.map((r) => [...r].map((ch, i) => (i >= half && SHADE[ch] ? SHADE[ch] : ch)).join(''));
}
const swap = (rows, map) => rows.map((r) => [...r].map((ch) => map[ch] || ch).join(''));

